"""Regenerate src/quick_herbalist/locales/base.pot from translatable strings.

Sources:
- static _("...") calls in src/quick_herbalist/*.py, screens/*.py, game/*.py
- name_key, description_key and ingredient keys in assets/recipes.yaml

tools/sprite_editor/ is never scanned, and logging/terminal strings stay out
because they are plain literals not passed to _(). Output is deterministic:
sorted msgids, fixed header, no timestamps.
"""

import ast
import sys
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
PKG_DIR = REPO_ROOT / "src" / "quick_herbalist"
DEFAULT_POT = PKG_DIR / "locales" / "base.pot"
RECIPES_YAML = PKG_DIR / "assets" / "recipes.yaml"

POT_HEADER = (
    "# Quick Herbalist translations\n"
    "# Regenerated by scripts/update_pot.py. Do not edit by hand.\n"
    "#\n"
    'msgid ""\n'
    'msgstr ""\n'
    '"Project-Id-Version: 0.1\\n"\n'
    '"Language: \\n"\n'
    '"MIME-Version: 1.0\\n"\n'
    '"Content-Type: text/plain; charset=UTF-8\\n"\n'
    '"Content-Transfer-Encoding: 8bit\\n"\n'
    '"Generated-By: update_pot.py\\n"\n'
)


def python_source_files():
    """Return the sorted Python files scanned for _() calls."""
    return sorted(
        list(PKG_DIR.glob("*.py"))
        + list((PKG_DIR / "screens").glob("*.py"))
        + list((PKG_DIR / "game").glob("*.py"))
    )


def extract_python_msgids(path):
    """Return static string literals passed as the sole argument to _() in one file."""
    tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    msgids = []
    for node in ast.walk(tree):
        if (
            isinstance(node, ast.Call)
            and isinstance(node.func, ast.Name)
            and node.func.id == "_"
            and len(node.args) == 1
            and isinstance(node.args[0], ast.Constant)
            and isinstance(node.args[0].value, str)
        ):
            msgids.append(node.args[0].value)
    return msgids


def recipe_msgids():
    """Return gettext msgids referenced by recipes.yaml (names, descriptions, ingredients)."""
    data = yaml.safe_load(RECIPES_YAML.read_text(encoding="utf-8"))
    msgids = []
    for recipe in data["recipes"]:
        msgids.append(recipe["name_key"])
        msgids.append(recipe["description_key"])
        msgids.extend(recipe["ingredients"].keys())
    return msgids


def _escape(msgid):
    """Escape a msgid for .pot output (backslash and double quote)."""
    return msgid.replace("\\", "\\\\").replace('"', '\\"')


def build_pot_content(msgids):
    """Build the full .pot text: fixed header plus one entry per unique msgid, sorted."""
    lines = [POT_HEADER, ""]
    for msgid in sorted(set(msgids)):
        lines.append(f'msgid "{_escape(msgid)}"')
        lines.append('msgstr ""')
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def main(argv=None):
    """Regenerate the .pot file; optional output path argument overrides base.pot."""
    argv = sys.argv[1:] if argv is None else argv
    msgids = []
    for path in python_source_files():
        msgids.extend(extract_python_msgids(path))
    msgids.extend(recipe_msgids())
    output = Path(argv[0]) if argv else DEFAULT_POT
    output.write_text(build_pot_content(msgids), encoding="utf-8")
    print(f"Wrote {len(set(msgids))} msgids to {output}")


if __name__ == "__main__":
    main()
